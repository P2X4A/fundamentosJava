package fundamentos;

public class variables {

	public static void main(String[] args) {
		//Permite almacenar un numero
		byte numeroByte = 8;
		
		//Permite almacenar un numero corto
		short numeroShort = 32;
		
		//Permite almacenar un numero entero
		int numeroInt = 64;
		
		//Permite almacenar un numero largo
		long numeroLargo = 128;
		
		//Permite almacenar un numero en Decimal
		float numeroFlotante = 0.129F;

		//Permite almacenar un numero decimal grande
		double numeroDecimalGrande = 1.929239d;
		
		//Permite datos falsos o verdaderos
		boolean verdadero = true;
		boolean falso = false;
		
		//Permite almacenar letras o numeros individuales
		char letra = 'P';
		char numero = 1;
		
	}

}
